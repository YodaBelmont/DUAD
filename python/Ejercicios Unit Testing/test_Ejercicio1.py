from Ejercicio1 import bubble_sort


def test_works_with_small_list():
    input_list = [13, 11, 8, 5, 7, 3, 12, 2, 9, 1]
    result = bubble_sort(input_list)
    assert result == [1, 2, 3, 5, 7, 8, 9, 11, 12, 13]


